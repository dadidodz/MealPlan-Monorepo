import { resetDatabase } from '../../../../test/support/reset-database';
import { PrismaService } from '../../../infrastructure/database/prisma.service';
import { PrismaIngredientReader } from './prisma-ingredient.reader';

describe('PrismaIngredientReader', () => {
    const prisma = new PrismaService();
    const reader = new PrismaIngredientReader(prisma);

    beforeEach(() => resetDatabase(prisma));
    afterAll(() => prisma.$disconnect());

    it('returns the ingredients whose code contains the fragment, by name, with their summary fields', async () => {
        await prisma.ingredient.createMany({
            data: [
                { name: 'Sucre', code: 'sucre' },
                { name: 'Farine complète', code: 'farine-complete', category: 'épicerie' },
                { name: 'Farine', code: 'farine' },
            ],
        });

        const found = await reader.searchByCode('farine');

        // ids are generated by the database
        expect(found.map(({ name, code, category }) => ({ name, code, category }))).toEqual([
            { name: 'Farine', code: 'farine', category: null },
            { name: 'Farine complète', code: 'farine-complete', category: 'épicerie' },
        ]);
        expect(Object.keys(found[0]).sort((a, b) => a.localeCompare(b))).toEqual([
            'category',
            'code',
            'id',
            'name',
        ]);
    });

    it('returns at most 10 ingredients', async () => {
        await prisma.ingredient.createMany({
            data: Array.from({ length: 12 }, (_, i) => ({
                name: `Épice ${i}`,
                code: `epice-${i}`,
            })),
        });

        expect(await reader.searchByCode('epice')).toHaveLength(10);
    });

    it('returns nothing when no code matches', async () => {
        await prisma.ingredient.create({ data: { name: 'Sel', code: 'sel' } });

        expect(await reader.searchByCode('poivre')).toEqual([]);
    });
});
